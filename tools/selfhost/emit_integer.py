#!/usr/bin/env python3
"""Regenerate the tagged-Int x64 emitter; --check verifies canonical parity.

GNU binutils are development tools only. The checked-in .mgn emitter is compiled
by the 1.9 seed and emits all runtime bytes through the native Machine backend.
No assembler or external integer library is required by generated applications.
"""
import argparse
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'compiler/mgnc/native/integer.S'
OUTPUT = ROOT / 'compiler/mgnc/src/WholeInteger/integer.mgn'
ENTRIES = {
    'mgn_add': ('addLabel', 200), 'mgn_sub': ('subLabel', 201),
    'mgn_mul': ('mulLabel', 202), 'mgn_div': ('divLabel', 203),
    'mgn_rem': ('remLabel', 204), 'mgn_cmp': ('compareLabel', 205),
    'mgn_neg': ('negateLabel', 206), 'mgn_signed': ('fromSignedLabel', 207),
    'mgn_unsigned': ('fromUnsignedLabel', 208), 'mgn_word': ('toWordLabel', 209),
    'mgn_construct': ('constructLabel', 210),
}
EXTERNAL = {'mgn_allocate': 'allocateLabel', 'mgn_allocation_failure': 'allocationFailure',
            'mgn_zero_failure': '5'}


def generate():
    with tempfile.TemporaryDirectory(prefix='mgn-integer-') as temporary:
        obj = Path(temporary) / 'integer.o'
        subprocess.run(['as', '--64', str(SOURCE), '-o', str(obj)], check=True)
        relocations = {}
        for line in subprocess.check_output(['objdump', '-r', str(obj)], text=True).splitlines():
            match = re.match(r'([0-9a-f]+)\s+R_X86_64_PLT32\s+(\w+)-', line)
            if match:
                relocations[int(match[1], 16)] = match[2]
        disassembly = subprocess.check_output(
            ['objdump', '-d', '-Mintel', '--insn-width=16', str(obj)], text=True)
    lines = [r'namespace Mgnc\WholeInteger;',
             r'use Mgnc\Machine\{Code,raw,label,jump};',
             r'use Mgnc\WholeABI\{allocateLabel,allocationFailure};']
    for constant, value in ENTRIES.values():
        lines.append(f'public let {constant}:Int={value};')
    lines += [
        '// Generated by tools/selfhost/emit_integer.py from compiler/mgnc/native/integer.S.',
        '// Internal tagged Int ABI: RAX lhs / RCX rhs -> RAX; compare returns raw -1/0/1.',
        '// Raw constructors take RAX. toWord returns raw RAX, signed64 validity RDX,',
        '// unsigned64 validity RCX. Construct takes RSI limbs / RCX count / RDX sign.',
        '// All helpers preserve the language callee saves and R15 runtime context.',
        '// Descriptor0 bigint: header24, sign24, count32, packed radix2^30 limbs40.',
        '// Private checked mmap scratch contains no references. Operands are copied',
        '// before the single managed allocation and are never dereferenced afterward.',
        '// Local displacements are relative within the unchanged instruction stream;',
        '// external helper calls/failures use ordinary Machine jump relocations.',
        'public let emit:Function(Code):Code=function(initial:Code):Code{',
        ' var code:Code=initial;',
    ]
    pending = []

    def flush():
        while pending:
            chunk = pending[:48]
            del pending[:48]
            lines.append(' code=raw(code,List<Int>[' + ','.join(map(str, chunk)) + ']);')

    for line in disassembly.splitlines():
        symbol = re.match(r'^([0-9a-f]+) <(\w+)>:', line)
        if symbol:
            flush()
            name = symbol[2]
            lines.append('// ' + name)
            if name in ENTRIES:
                lines.append(' code=label(code,' + ENTRIES[name][0] + ');')
            continue
        instruction = re.match(r'^\s*([0-9a-f]+):\s*((?:[0-9a-f]{2}\s)+)\s*(.*)', line)
        if not instruction:
            continue
        offset = int(instruction[1], 16)
        octets = bytes.fromhex(instruction[2])
        targets = [(position, target) for position, target in relocations.items()
                   if offset <= position < offset + len(octets)]
        if targets:
            flush()
            assert len(targets) == 1
            position, target = targets[0]
            prefix = octets[:position-offset]
            assert len(octets) == len(prefix) + 4
            wanted = ENTRIES[target][0] if target in ENTRIES else EXTERNAL[target]
            lines.append(' code=jump(code,List<Int>[' + ','.join(map(str, prefix)) + '],' + wanted + ');')
        else:
            pending.extend(octets)
    flush()
    lines += [' code', '};']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if OUTPUT.read_text() != content:
            raise SystemExit('Tagged integer emitter differs; run tools/selfhost/emit_integer.py')
        print('INTEGER_EMITTER_PARITY_OK')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
