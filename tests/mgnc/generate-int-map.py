#!/usr/bin/env python3
"""Generate a persistent Int64 radix map with a five-level low-key path."""
import argparse
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
TARGET=ROOT/"compiler/mgnc/src/IntMap/map.mgn"
def generate():
 lines=["namespace Mgnc\\IntMap;","// Generated by tests/mgnc/generate-int-map.py; nonnegative Int64 keys.",
 "use Mgnc\\Data\\{Diagnostic,Span,problem};",
 "template replaceSlot<T>=function(values:List<T>,index:Int,value:T,blank:T):List<T>{",
 " var result:List<T>=List<T>[];var cursor:Int=0;let count:Int=branch when{values->length()>index=>values->length(),else=>index+1};",
 " loop while(cursor<count){result=result->append(branch when{cursor==index=>value,else=>branch on values->at(cursor){Result<T,IndexError>::Ok(found:T)=>found,Result<T,IndexError>::Err(error:IndexError)=>blank}});cursor=cursor+1;};result",
 "};"]
 for level in range(15,0,-1):
  child="Int" if level==15 else f"Level{level+1}"
  lines.append(f"public type Level{level}=product{{children:List<{child}>;}};")
 lines+=["public type Map=product{children:List<Level1>;small:Level11;};","public let create:Function():Map=function():Map{Map{children:List<Level1>[],small:Level11{children:List<Level12>[]}}};"]
 for operation in ["get","put"]:
  out="Int" if operation=="get" else "Map"
  lines.append(f"public let {operation}:Function(Map,Int"+(",Int" if operation=="put" else "")+f"):Result<{out},Diagnostic>=function(table:Map,key:Int"+(",value:Int" if operation=="put" else "")+f"):Result<{out},Diagnostic>{{")
  lines.append(f' branch when{{key<0=>{{return Result<{out},Diagnostic>::Err(problem("internal",Span{{start:0,end:0,line:1,column:1}},"negative radix key"));}},else=>unit}};')
  for small in [True,False]:
   if small:
    lines+=[" branch when{key<1048576=>{"," let node11:Level11=table->small;"]
   for level in range(12 if small else 1,16):
    parent="table" if level==1 else f"node{level-1}"
    child="Int" if level==15 else f"Level{level+1}"
    divisor=16**(16-level)
    missing='{return Result<Int,Diagnostic>::Ok(-2);}' if operation=="get" else f"Level{level}{{children:List<{child}>[]}}"
    lines.append(f" let node{level}:Level{level}=branch on {parent}->children->at(key/{divisor}%16){{Result<Level{level},IndexError>::Ok(found:Level{level})=>found,Result<Level{level},IndexError>::Err(error:IndexError)=>{missing}}};")
   if operation=="get":
    lines.append((" return " if small else " ")+"branch on node15->children->at(key%16){Result<Int,IndexError>::Ok(found:Int)=>Result<Int,Diagnostic>::Ok(found),Result<Int,IndexError>::Err(error:IndexError)=>Result<Int,Diagnostic>::Ok(-2)}"+(";" if small else ""))
   else:
    lines.append(" let updated15:Level15=Level15{children:replaceSlot<Int>(node15->children,key%16,value,-2)};")
    for level in range(14,10 if small else 0,-1):
     child=f"Level{level+1}";grandchild="Int" if level==14 else f"Level{level+2}"
     divisor=16**(15-level)
     lines.append(f" let updated{level}:Level{level}=Level{level}{{children:replaceSlot<{child}>(node{level}->children,key/{divisor}%16,updated{level+1},{child}{{children:List<{grandchild}>[]}})}};")
    lines.append(" return Result<Map,Diagnostic>::Ok(Map{children:table->children,small:updated11});" if small else " Result<Map,Diagnostic>::Ok(Map{children:replaceSlot<Level1>(table->children,key/1152921504606846976%16,updated1,Level1{children:List<Level2>[]}),small:table->small})")
   if small:lines.append(" },else=>unit};")
  lines.append("};")
 return "\n".join(lines)+"\n"
def main():
 p=argparse.ArgumentParser();p.add_argument("--check",action="store_true");a=p.parse_args();text=generate()
 if a.check:assert TARGET.read_text()==text
 else:TARGET.write_text(text)
 print("V150_INT_MAP_REPRODUCIBLE")
if __name__=="__main__":main()
